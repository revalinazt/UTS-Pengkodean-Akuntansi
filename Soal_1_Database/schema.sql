CREATE TABLE chart_of_accounts (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code varchar(20) NOT NULL UNIQUE,
    account_name varchar(150) NOT NULL,
    account_type varchar(20) NOT NULL,
    normal_balance varchar(6) NOT NULL,
    parent_account_id bigint,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    created_by varchar(100) NOT NULL,
    CONSTRAINT chk_accounts_code_not_blank CHECK (btrim(account_code) <> ''),
    CONSTRAINT chk_accounts_name_not_blank CHECK (btrim(account_name) <> ''),
    CONSTRAINT chk_accounts_type CHECK (
        account_type IN ('ASSET', 'LIABILITY', 'EQUITY', 'REVENUE', 'EXPENSE')
    ),
    CONSTRAINT chk_accounts_normal_balance CHECK (
        normal_balance IN ('DEBIT', 'CREDIT')
    ),
    CONSTRAINT fk_accounts_parent
        FOREIGN KEY (parent_account_id)
        REFERENCES chart_of_accounts (account_id)
        ON DELETE RESTRICT
);

CREATE TABLE journal_headers (
    journal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_number varchar(30) NOT NULL UNIQUE,
    journal_date date NOT NULL,
    description text NOT NULL DEFAULT '',
    status varchar(10) NOT NULL DEFAULT 'DRAFT',
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    created_by varchar(100) NOT NULL,
    posted_at timestamptz,
    posted_by varchar(100),
    CONSTRAINT chk_journal_number_not_blank CHECK (btrim(journal_number) <> ''),
    CONSTRAINT chk_journal_status CHECK (
        status IN ('DRAFT', 'POSTED', 'VOID')
    ),
    CONSTRAINT chk_journal_posting_actor_pair CHECK (
        (posted_at IS NULL) = (posted_by IS NULL)
    ),
    CONSTRAINT chk_posted_journal_has_posting_metadata CHECK (
        status <> 'POSTED' OR posted_at IS NOT NULL
    ),
    CONSTRAINT chk_draft_journal_is_not_posted CHECK (
        status <> 'DRAFT' OR posted_at IS NULL
    )
);

CREATE TABLE journal_lines (
    journal_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id bigint NOT NULL,
    line_number integer NOT NULL,
    account_id bigint NOT NULL,
    description text NOT NULL DEFAULT '',
    debit numeric(18, 2) NOT NULL DEFAULT 0,
    credit numeric(18, 2) NOT NULL DEFAULT 0,
    CONSTRAINT uq_journal_lines_number UNIQUE (journal_id, line_number),
    CONSTRAINT chk_journal_line_number_positive CHECK (line_number > 0),
    CONSTRAINT chk_journal_line_amounts_nonnegative CHECK (
        debit >= 0 AND credit >= 0
    ),
    CONSTRAINT chk_journal_line_one_side_only CHECK (
        (debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0)
    ),
    CONSTRAINT fk_journal_lines_header
        FOREIGN KEY (journal_id)
        REFERENCES journal_headers (journal_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_journal_lines_account
        FOREIGN KEY (account_id)
        REFERENCES chart_of_accounts (account_id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_journal_headers_date
    ON journal_headers (journal_date);

CREATE INDEX idx_journal_lines_account
    ON journal_lines (account_id);
