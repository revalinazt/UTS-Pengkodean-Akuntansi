CREATE SEQUENCE inventory_journal_number_seq;

CREATE TABLE products (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(30) NOT NULL UNIQUE,
    product_name varchar(150) NOT NULL,
    inventory_account_id bigint NOT NULL,
    stock_on_hand numeric(18, 3) NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    CONSTRAINT chk_products_sku_not_blank CHECK (btrim(sku) <> ''),
    CONSTRAINT chk_products_name_not_blank CHECK (btrim(product_name) <> ''),
    CONSTRAINT chk_products_stock_nonnegative CHECK (stock_on_hand >= 0),
    CONSTRAINT fk_products_inventory_account
        FOREIGN KEY (inventory_account_id)
        REFERENCES chart_of_accounts (account_id)
        ON DELETE RESTRICT
);

CREATE TABLE inventory_transactions (
    inventory_transaction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL,
    transaction_type varchar(10) NOT NULL,
    adjustment_direction varchar(3),
    quantity numeric(18, 3) NOT NULL,
    unit_cost numeric(18, 4) NOT NULL,
    offset_account_id bigint NOT NULL,
    transaction_date date NOT NULL DEFAULT CURRENT_DATE,
    description text NOT NULL DEFAULT '',
    created_by varchar(100) NOT NULL,
    journal_id bigint NOT NULL UNIQUE,
    CONSTRAINT chk_inventory_type CHECK (
        transaction_type IN ('PURCHASE', 'SALE', 'ADJUSTMENT')
    ),
    CONSTRAINT chk_inventory_adjustment_direction CHECK (
        (transaction_type = 'ADJUSTMENT'
            AND adjustment_direction IS NOT NULL
            AND adjustment_direction IN ('IN', 'OUT'))
        OR (transaction_type IN ('PURCHASE', 'SALE')
            AND adjustment_direction IS NULL)
    ),
    CONSTRAINT chk_inventory_quantity_positive CHECK (quantity > 0),
    CONSTRAINT chk_inventory_unit_cost_positive CHECK (unit_cost > 0),
    CONSTRAINT fk_inventory_transactions_product
        FOREIGN KEY (product_id)
        REFERENCES products (product_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_transactions_offset_account
        FOREIGN KEY (offset_account_id)
        REFERENCES chart_of_accounts (account_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_transactions_journal
        FOREIGN KEY (journal_id)
        REFERENCES journal_headers (journal_id)
        ON DELETE RESTRICT
);

CREATE OR REPLACE FUNCTION trg_update_stock_and_journal()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_stock_delta numeric(18, 3);
    v_inventory_account_id bigint;
    v_debit_account_id bigint;
    v_credit_account_id bigint;
    v_amount numeric(18, 2);
    v_journal_id bigint;
BEGIN
    IF NEW.transaction_type = 'PURCHASE'
       OR (NEW.transaction_type = 'ADJUSTMENT'
           AND NEW.adjustment_direction = 'IN') THEN
        v_stock_delta := NEW.quantity;
        v_debit_account_id := NULL;
        v_credit_account_id := NEW.offset_account_id;
    ELSE
        v_stock_delta := -NEW.quantity;
        v_debit_account_id := NEW.offset_account_id;
        v_credit_account_id := NULL;
    END IF;

    v_amount := round(NEW.quantity * NEW.unit_cost, 2);
    IF v_amount <= 0 THEN
        RAISE EXCEPTION 'Nilai transaksi persediaan harus lebih besar dari nol'
            USING ERRCODE = 'check_violation';
    END IF;

    UPDATE products
       SET stock_on_hand = stock_on_hand + v_stock_delta
     WHERE product_id = NEW.product_id
       AND stock_on_hand + v_stock_delta >= 0
     RETURNING inventory_account_id INTO v_inventory_account_id;

    IF NOT FOUND THEN
        IF EXISTS (
            SELECT 1 FROM products WHERE product_id = NEW.product_id
        ) THEN
            RAISE EXCEPTION 'Stok produk % tidak mencukupi', NEW.product_id
                USING ERRCODE = 'check_violation';
        ELSE
            RAISE EXCEPTION 'Produk % tidak ditemukan', NEW.product_id
                USING ERRCODE = 'foreign_key_violation';
        END IF;
    END IF;

    IF NEW.transaction_type = 'PURCHASE'
       OR (NEW.transaction_type = 'ADJUSTMENT'
           AND NEW.adjustment_direction = 'IN') THEN
        v_debit_account_id := v_inventory_account_id;
    ELSE
        v_credit_account_id := v_inventory_account_id;
    END IF;

    IF v_debit_account_id = v_credit_account_id THEN
        RAISE EXCEPTION 'Akun persediaan dan akun lawan harus berbeda'
            USING ERRCODE = 'check_violation';
    END IF;

    INSERT INTO journal_headers (
        journal_number,
        journal_date,
        description,
        status,
        created_by,
        posted_at,
        posted_by
    ) VALUES (
        'INV-' || lpad(nextval('inventory_journal_number_seq')::text, 10, '0'),
        NEW.transaction_date,
        'Persediaan ' || NEW.transaction_type || ' #' || NEW.inventory_transaction_id
            || CASE WHEN NEW.description = '' THEN '' ELSE ': ' || NEW.description END,
        'POSTED',
        NEW.created_by,
        transaction_timestamp(),
        NEW.created_by
    ) RETURNING journal_id INTO v_journal_id;

    INSERT INTO journal_lines (
        journal_id, line_number, account_id, description, debit, credit
    ) VALUES
        (v_journal_id, 1, v_debit_account_id, 'Nilai persediaan', v_amount, 0),
        (v_journal_id, 2, v_credit_account_id, 'Nilai persediaan', 0, v_amount);

    NEW.journal_id := v_journal_id;
    RETURN NEW;
END;
$$;

CREATE TRIGGER inventory_transaction_stock_and_journal
BEFORE INSERT ON inventory_transactions
FOR EACH ROW
EXECUTE FUNCTION trg_update_stock_and_journal();
